import { spawn } from 'node:child_process'
import { readFile, readdir, stat, rm, rename } from 'node:fs/promises'
import { join } from 'node:path'
import { randomUUID } from 'node:crypto'
import { fail } from './errors.js'

export function runProcess(bin, args, { signal, timeoutMs = 180_000, capture = false } = {}) {
  return new Promise((resolve, reject) => {
    let output = ''
    let failure
    const child = spawn(bin, args, { stdio: ['ignore', capture ? 'pipe' : 'ignore', 'ignore'] })
    const stop = () => {
      failure ??= fail('TRANSCODE_CANCELLED', '媒体处理已取消', 503)
      child.kill('SIGTERM')
      killTimer ??= setTimeout(() => child.kill('SIGKILL'), 2000)
    }
    let killTimer
    const timer = setTimeout(() => { failure = fail('TRANSCODE_TIMEOUT', '媒体处理超时', 504); stop() }, timeoutMs)
    const onAbort = () => stop()
    signal?.addEventListener('abort', onAbort, { once: true })
    if (signal?.aborted) stop()
    child.stdout?.on('data', chunk => {
      output += chunk
      if (output.length > 128_000) { failure = fail('PROBE_FAILED', '媒体信息过大'); stop() }
    })
    child.once('error', () => { failure = fail('TRANSCODE_UNAVAILABLE', 'FFmpeg/FFprobe 无法启动') })
    child.once('close', code => {
      clearTimeout(timer)
      clearTimeout(killTimer)
      signal?.removeEventListener('abort', onAbort)
      if (failure) reject(failure)
      else if (code !== 0) reject(fail('TRANSCODE_FAILED', '媒体转码失败，来源可能已失效'))
      else resolve(output)
    })
  })
}

export function parsePlaylist(text) {
  const segments = []
  let duration
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim()
    if (line.startsWith('#EXTINF:')) duration = Number(line.slice(8).split(',')[0])
    else if (line && !line.startsWith('#') && Number.isFinite(duration) && duration > 0) {
      // Only files generated by this encoder; never accept URI/path injection.
      if (!/^s\d{6}\.ts$/.test(line) || duration > 3) throw fail('PLAYLIST_INVALID', '转码分片列表无效')
      segments.push({ name: line, duration })
      duration = undefined
    }
  }
  return segments
}

export async function directorySize(dir) {
  let size = 0
  for (const file of await readdir(dir, { withFileTypes: true })) {
    if (file.isFile()) size += await stat(join(dir, file.name)).then(info => info.size).catch(error => { if (error.code === 'ENOENT') return 0; throw error })
  }
  return size
}

/** Original playback path: bounded download, CENC decryption and MP4 stream-copy.
 * No real-time video encoding or live manifest dependency; publish complete files.
 */
export async function prepareFile(job, { source, ffmpeg = '/usr/bin/ffmpeg', ffprobe = '/usr/bin/ffprobe', outputLimit = 128 * 1024 ** 2 } = {}) {
  const input = join(job.dir, 'source.mp4')
  const partial = join(job.dir, 'output.part.mp4')
  const output = join(job.dir, 'output.mp4')
  const signal = job.controller.signal
  try {
    const resolved = await source(job.episode.id, input, signal)
    const decrypt = resolved.key ? ['-decryption_key', resolved.key] : []
    const probeArgs = ['-v', 'quiet', '-max_alloc', '67108864', '-protocol_whitelist', 'file,pipe', '-f', 'mov']
    const info = JSON.parse(await runProcess(ffprobe, [...probeArgs, ...decrypt, '-i', resolved.path, '-show_entries', 'stream=codec_type,codec_name:format=duration', '-of', 'json'], { signal, timeoutMs: 20_000, capture: true }))
    const video = info.streams?.find(row => row.codec_type === 'video')
    if (!video || !['h264', 'hevc'].includes(video.codec_name)) throw fail('SOURCE_CODEC', '原视频编码暂不支持，请更换剧集')
    await runProcess(ffmpeg, ['-v', 'error', '-max_alloc', '67108864', '-nostdin', '-y', '-threads', '2', '-protocol_whitelist', 'file,pipe', '-f', 'mov', ...decrypt, '-i', resolved.path,
      '-map', '0:v:0', '-map', '0:a:0?', '-c', 'copy', '-tag:v', video.codec_name === 'hevc' ? 'hvc1' : 'avc1',
      '-movflags', '+faststart', '-fs', String(outputLimit + 1), partial], { signal, timeoutMs: 120_000 })
    if ((await stat(partial)).size > outputLimit) throw fail('OUTPUT_TOO_LARGE', '该集文件超过大小限制', 413)
    const verified = JSON.parse(await runProcess(ffprobe, [...probeArgs, '-i', partial, '-show_entries', 'format=duration', '-of', 'json'], { signal, timeoutMs: 20_000, capture: true }))
    const duration = Number(verified.format?.duration)
    const originalDuration = Number(info.format?.duration)
    if (!(duration > 0) || originalDuration > 0 && duration < originalDuration - Math.max(0.5, originalDuration * 0.005)) throw fail('MEDIA_INCOMPLETE', '原视频文件不完整，请重试')
    await rename(partial, output)
    job.duration = duration
    job.fileReady = true
    job.done = true
  } finally {
    await Promise.all([rm(input, { force: true }), rm(partial, { force: true })])
  }
}

export function videoProfile(stream, maxEdge = 960) {
  let w = Number(stream?.width)
  let h = Number(stream?.height)
  const [sarW, sarH] = String(stream?.sample_aspect_ratio ?? '1:1').split(':').map(Number)
  if (sarW > 0 && sarH > 0) w *= sarW / sarH
  const rotation = Number(stream?.side_data_list?.find(row => row.rotation !== undefined)?.rotation ?? stream?.tags?.rotate ?? 0)
  if (Math.abs(rotation % 180) === 90) [w, h] = [h, w]
  if (!(w > 0 && h > 0) || !Number.isFinite(w / h)) throw fail('VIDEO_DIMENSIONS', '来源画幅信息不可用')
  const scale = maxEdge / Math.max(w, h)
  return { width: Math.max(2, Math.floor(w * scale / 2) * 2), height: Math.max(2, Math.floor(h * scale / 2) * 2) }
}
export function seriesProfile(episodeId) {
  let resolve, reject
  const profile = { id: `aspect-v2-${randomUUID()}`, owner: episodeId, state: 'pending' }
  profile.ready = new Promise((yes, no) => { resolve = yes; reject = no })
  profile.ready.catch(() => {})
  profile.resolve = value => { if (profile.state === 'pending') { profile.state = 'ready'; profile.value = value; resolve(value) } }
  profile.fail = error => { if (profile.state === 'pending') { profile.state = 'failed'; reject(error) } }
  return profile
}
async function waitProfile(profile, signal) {
  if (signal.aborted) throw fail('TRANSCODE_CANCELLED', '媒体处理已取消', 503)
  let abort
  const cancelled = new Promise((_, reject) => { abort = () => reject(fail('TRANSCODE_CANCELLED', '媒体处理已取消', 503)); signal.addEventListener('abort', abort, { once: true }) })
  try { return await Promise.race([profile.ready, cancelled]) }
  finally { signal.removeEventListener('abort', abort) }
}

/** Publish only segment files renamed out of *.tmp by FFmpeg. */
export async function encodeEpisode(job, { source, ffmpeg = '/usr/bin/ffmpeg', ffprobe = '/usr/bin/ffprobe', width, height, profile, maxEdge = 960, timeoutMs = 180_000, outputLimit = 128 * 1024 ** 2 }) {
  const signal = job.controller.signal
  const input = join(job.dir, 'source.mp4')
  let polling = false
  let pollError
  const refresh = async () => {
    if (polling) return
    polling = true
    try {
      let text
      try { text = await readFile(join(job.dir, 'episode.m3u8'), 'utf8') } catch (error) { if (error.code === 'ENOENT') return; throw error }
      const rows = parsePlaylist(text)
      const complete = []
      for (const segment of rows) {
        const info = await stat(join(job.dir, segment.name))
        if (!info.isFile() || !info.size) throw fail('SEGMENT_INVALID', '媒体分片不可用')
        complete.push(segment)
      }
      job.segments = complete
      if (await directorySize(job.dir) > outputLimit + job.sourceSize) throw fail('OUTPUT_TOO_LARGE', '该集转码结果超过大小限制', 413)
    } catch (error) { pollError = error; job.controller.abort() }
    finally { polling = false }
  }
  let poller
  try {
    const resolved = await source(job.episode.id, input, signal)
    job.sourceSize = (await stat(resolved.path)).size
    const decryption = resolved.key ? ['-decryption_key', resolved.key] : []
    const probe = JSON.parse(await runProcess(ffprobe, ['-v', 'quiet', '-max_alloc', '67108864', '-protocol_whitelist', 'file,pipe', '-f', 'mov', ...decryption, '-i', resolved.path, '-show_entries', 'stream=codec_type,width,height,sample_aspect_ratio:stream_tags=rotate:stream_side_data=rotation', '-of', 'json'], { signal, timeoutMs: 20_000, capture: true }))
    const video = probe.streams?.find(stream => stream.codec_type === 'video')
    if (!video) throw fail('NO_VIDEO', '来源没有视频轨道')
    if (profile) {
      if (profile.owner === job.episode.id) profile.resolve(videoProfile(video, maxEdge))
      ;({ width, height } = await waitProfile(profile, signal))
    } else if (!width || !height) ({ width, height } = videoProfile(video, maxEdge))
    job.outputProfile = { width, height }
    const hasAudio = probe.streams.some(stream => stream.codec_type === 'audio')
    const args = ['-hide_banner', '-loglevel', 'error', '-max_alloc', '67108864', '-nostdin', '-y', '-threads', '2', '-protocol_whitelist', 'file,pipe', '-f', 'mov', ...decryption, '-i', resolved.path,
      ...(!hasAudio ? ['-f', 'lavfi', '-i', 'anullsrc=r=48000:cl=stereo'] : []),
      '-map', '0:v:0', '-map', hasAudio ? '0:a:0' : '1:a:0',
      '-vf', `scale=w=trunc(iw*sar/2)*2:h=ih,setsar=1,scale=${width}:${height}:force_original_aspect_ratio=decrease:force_divisible_by=2,pad=${width}:${height}:(ow-iw)/2:(oh-ih)/2,setsar=1,fps=25`,
      '-c:v', 'libx264', '-preset', 'veryfast', '-profile:v', 'main', '-pix_fmt', 'yuv420p', '-level:v', '3.1',
      '-threads', '2', '-filter_threads', '1', '-crf', '24', '-maxrate', '1800k', '-bufsize', '3600k',
      '-g', '50', '-keyint_min', '50', '-sc_threshold', '0', '-force_key_frames', 'expr:gte(t,n_forced*2)',
      '-c:a', 'aac', '-ar', '48000', '-ac', '2', '-b:a', '96k', '-af', 'aresample=async=1:first_pts=0',
      '-shortest', '-max_muxing_queue_size', '1024', '-f', 'hls', '-hls_time', '2', '-hls_list_size', '0',
      '-hls_playlist_type', 'event', '-hls_flags', 'independent_segments+temp_file',
      '-hls_segment_filename', join(job.dir, 's%06d.ts'), join(job.dir, 'episode.m3u8')]
    poller = setInterval(() => { void refresh() }, 100)
    await runProcess(ffmpeg, args, { signal, timeoutMs })
    clearInterval(poller)
    // A poll may be in flight. Await its completion without publishing stale data.
    while (polling) await new Promise(resolve => setTimeout(resolve, 5))
    await refresh()
    if (pollError) throw pollError
    if (!job.segments.length) throw fail('NO_SEGMENTS', '转码未生成可播放分片')
    job.done = true
  } catch (error) {
    if (profile?.owner === job.episode.id) profile.fail(pollError ?? error)
    throw pollError ?? error
  }
  finally {
    clearInterval(poller)
    while (polling) await new Promise(resolve => setTimeout(resolve, 5))
    // Production source is always this private file. Tests may return a fixture
    // path; never delete an injected path outside this job directory.
    await rm(input, { force: true })
  }
}
